        boneIndex: Int
    ) {
        writer.println("    AnimationCurveNode: $curveNodeId, \"AnimCurveNode::$channel\", \"\" {")
        writer.println("        Properties70:  {")
        writer.println("            P: \"d|X\", \"Number\", \"\", \"A\",0")
        writer.println("            P: \"d|Y\", \"Number\", \"\", \"A\",0")
        writer.println("            P: \"d|Z\", \"Number\", \"\", \"A\",0")
        writer.println("        }")
        writer.println("    }")
        writer.println()
    }
    
