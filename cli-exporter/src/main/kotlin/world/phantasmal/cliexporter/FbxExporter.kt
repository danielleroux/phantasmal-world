    private fun writeConnections(
        writer: PrintWriter,
        ninjaObject: NinjaObject<*, *>,
        motion: NjMotion,
        curveIds: Pair<Long, Long>
    ) {
        writer.println("Connections:  {")
        
        // Connect bones to their parents
        val boneIndices = mutableMapOf<NinjaObject<*, *>, Int>()
        writeBoneConnections(writer, ninjaObject, boneIndices, -1)
        
        // Connect animation stack to layer
        writer.println("    C: \"OO\",3456789012,2345678901")
        writer.println()
        
        // Connect animation curves to bones
        writeAnimationConnections(writer, ninjaObject, motion, boneIndices, curveIds.first, curveIds.second)
        
        writer.println("}")
        writer.println()
    }
    
    private fun writeBoneConnections(
        writer: PrintWriter,
        obj: NinjaObject<*, *>,
        boneIndices: MutableMap<NinjaObject<*, *>, Int>,
        parentIndex: Int
    ): Int {
        if (obj.evaluationFlags.skip) {
            for (child in obj.children) {
                writeBoneConnections(writer, child, boneIndices, parentIndex)
            }
            return parentIndex
        }
        
        val boneIndex = boneIndices.size
        boneIndices[obj] = boneIndex
        val modelId = 1000000000L + boneIndex
        
        if (parentIndex >= 0) {
            val parentModelId = 1000000000L + parentIndex
            writer.println("    C: \"OO\",$modelId,$parentModelId")
        }
        
        if (!obj.evaluationFlags.breakChildTrace) {
            for (child in obj.children) {
                writeBoneConnections(writer, child, boneIndices, boneIndex)
            }
        }
        
        return boneIndex
    }
    
    private fun writeAnimationConnections(
        writer: PrintWriter,
        ninjaObject: NinjaObject<*, *>,
        motion: NjMotion,
        boneIndices: Map<NinjaObject<*, *>, Int>,
        startCurveNodeId: Long,
        startCurveId: Long
    ) {
        val boneCount = ninjaObject.boneCount()
        var curveNodeId = startCurveNodeId
        var curveId = startCurveId
        
        for ((boneIndex, motionData) in motion.motionData.withIndex()) {
            if (boneIndex >= boneCount) {
                break
            }
            
            val bone = ninjaObject.getBone(boneIndex) ?: continue
            val nodeIndex = boneIndices[bone] ?: continue
            val modelId = 1000000000L + nodeIndex
            
            for (track in motionData.tracks) {
                when (track) {
                    is NjKeyframeTrack.Position -> {
                        // Connect curve node to bone
                        writer.println("    C: \"OP\",$curveNodeId,$modelId, \"Lcl Translation\"")
                        // Connect curve node to layer
                        writer.println("    C: \"OO\",$curveNodeId,3456789012")
                        // Connect curves to curve node
                        writer.println("    C: \"OP\",$curveId,$curveNodeId, \"d|X\"")
                        writer.println("    C: \"OP\",${curveId + 1},$curveNodeId, \"d|Y\"")
                        writer.println("    C: \"OP\",${curveId + 2},$curveNodeId, \"d|Z\"")
                        
                        curveNodeId++
                        curveId += 3
                    }
                    is NjKeyframeTrack.EulerAngles -> {
                        writer.println("    C: \"OP\",$curveNodeId,$modelId, \"Lcl Rotation\"")
                        writer.println("    C: \"OO\",$curveNodeId,3456789012")
                        writer.println("    C: \"OP\",$curveId,$curveNodeId, \"d|X\"")
                        writer.println("    C: \"OP\",${curveId + 1},$curveNodeId, \"d|Y\"")
                        writer.println("    C: \"OP\",${curveId + 2},$curveNodeId, \"d|Z\"")
                        
                        curveNodeId++
                        curveId += 3
                    }
                    is NjKeyframeTrack.Scale -> {
                        writer.println("    C: \"OP\",$curveNodeId,$modelId, \"Lcl Scaling\"")
                        writer.println("    C: \"OO\",$curveNodeId,3456789012")
                        writer.println("    C: \"OP\",$curveId,$curveNodeId, \"d|X\"")
                        writer.println("    C: \"OP\",${curveId + 1},$curveNodeId, \"d|Y\"")
                        writer.println("    C: \"OP\",${curveId + 2},$curveNodeId, \"d|Z\"")
                        
                        curveNodeId++
                        curveId += 3
                    }
                    is NjKeyframeTrack.Quaternion -> {
                        // Skip quaternion tracks for now
                    }
                }
            }
        }
    }
    
    private fun frameToKTime(frame: Int): Long {
        return (frame / PSO_FRAME_RATE * KTIME_PER_SECOND).toLong()
    }
