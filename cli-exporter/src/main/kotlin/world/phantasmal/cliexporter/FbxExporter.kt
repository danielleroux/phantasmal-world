        writer.println("Documents:  {")
        writer.println("    Count: 1")
        writer.println("    Document: 1234567890, \"\", \"Scene\" {")
        writer.println("        Properties70:  {")
        writer.println("        }")
        writer.println("        RootNode: 0")
        writer.println("    }")
        writer.println("}")
        writer.println()
    }
    
    private fun writeDefinitions(writer: PrintWriter, boneCount: Int, motion: NjMotion) {
        writer.println("Definitions:  {")
        writer.println("    Version: 100")
        writer.println("    Count: 4")
        writer.println("    ObjectType: \"Model\" {")
        writer.println("        Count: $boneCount")
        writer.println("    }")
        writer.println("    ObjectType: \"AnimationStack\" {")
        writer.println("        Count: 1")
        writer.println("    }")
        writer.println("    ObjectType: \"AnimationLayer\" {")
        writer.println("        Count: 1")
        writer.println("    }")
        writer.println("    ObjectType: \"AnimationCurveNode\" {")
        writer.println("        Count: ${motion.motionData.size * 3}") // Approximate
        writer.println("    }")
        writer.println("}")
        writer.println()
    }
    
    private fun writeObjects(writer: PrintWriter, ninjaObject: NinjaObject<*, *>, motion: NjMotion): Pair<Long, Long> {
        writer.println("Objects:  {")
        
        // Write bone models
        val boneIndices = mutableMapOf<NinjaObject<*, *>, Int>()
        writeBoneModels(writer, ninjaObject, boneIndices, -1)
        
        // Write animation stack
        writer.println("    AnimationStack: 2345678901, \"AnimStack::Take 001\", \"\" {")
        writer.println("        Properties70:  {")
        writer.println("            P: \"LocalStart\", \"KTime\", \"Time\", \"\",0")
        writer.println("            P: \"LocalStop\", \"KTime\", \"Time\", \"\",${frameToKTime(motion.frameCount - 1)}")
        writer.println("            P: \"ReferenceStart\", \"KTime\", \"Time\", \"\",0")
        writer.println("            P: \"ReferenceStop\", \"KTime\", \"Time\", \"\",${frameToKTime(motion.frameCount - 1)}")
        writer.println("        }")
        writer.println("    }")
        writer.println()
        
        // Write animation layer
        writer.println("    AnimationLayer: 3456789012, \"AnimLayer::BaseLayer\", \"\" {")
        writer.println("    }")
        writer.println()
        
        // Write animation curves for each bone
        val curveIds = writeAnimationCurves(writer, ninjaObject, motion, boneIndices)
        
        writer.println("}")
        writer.println()
        
        return curveIds
    }
    
    private fun writeBoneModels(
        writer: PrintWriter,
        obj: NinjaObject<*, *>,
        boneIndices: MutableMap<NinjaObject<*, *>, Int>,
        parentIndex: Int
    ): Int {
        if (obj.evaluationFlags.skip) {
            // Process children but don't create a bone for this object
            for (child in obj.children) {
                writeBoneModels(writer, child, boneIndices, parentIndex)
            }
            return parentIndex
        }
        
        val boneIndex = boneIndices.size
        boneIndices[obj] = boneIndex
        val modelId = 1000000000L + boneIndex
        
        writer.println("    Model: $modelId, \"Model::Bone_$boneIndex\", \"LimbNode\" {")
        writer.println("        Version: 232")
        writer.println("        Properties70:  {")
        
        if (!obj.evaluationFlags.noTranslate) {
            writer.println("            P: \"Lcl Translation\", \"Lcl Translation\", \"\", \"A\",${obj.position.x},${obj.position.y},${obj.position.z}")
        }
        
        if (!obj.evaluationFlags.noRotate) {
            // Convert radians to degrees
            val rx = Math.toDegrees(obj.rotation.x.toDouble())
            val ry = Math.toDegrees(obj.rotation.y.toDouble())
            val rz = Math.toDegrees(obj.rotation.z.toDouble())
            writer.println("            P: \"Lcl Rotation\", \"Lcl Rotation\", \"\", \"A\",$rx,$ry,$rz")
        }
        
        if (!obj.evaluationFlags.noScale) {
            writer.println("            P: \"Lcl Scaling\", \"Lcl Scaling\", \"\", \"A\",${obj.scale.x},${obj.scale.y},${obj.scale.z}")
        }
        
        writer.println("        }")
        writer.println("        Shading: T")
        writer.println("        Culling: \"CullingOff\"")
        writer.println("    }")
        writer.println()
        
        // Process children
        if (!obj.evaluationFlags.breakChildTrace) {
            for (child in obj.children) {
                writeBoneModels(writer, child, boneIndices, boneIndex)
            }
        }
        
        return boneIndex
    }
    
    private fun writeAnimationCurves(
        writer: PrintWriter,
        ninjaObject: NinjaObject<*, *>,
        motion: NjMotion,
        boneIndices: Map<NinjaObject<*, *>, Int>
    ): Pair<Long, Long> {
        val boneCount = ninjaObject.boneCount()
        var curveNodeId = 4000000000L
        var curveId = 5000000000L
        
        // Map to store curve node IDs for connections
        val curveNodeIds = mutableMapOf<Pair<Int, String>, Long>()
        
        for ((boneIndex, motionData) in motion.motionData.withIndex()) {
            if (boneIndex >= boneCount) {
                break // More animation tracks than bones
            }
            
            val bone = ninjaObject.getBone(boneIndex) ?: continue
            val nodeIndex = boneIndices[bone] ?: continue
            
            for (track in motionData.tracks) {
                when (track) {
                    is NjKeyframeTrack.Position -> {
                        writeAnimationCurveNode(writer, curveNodeId, "T", nodeIndex)
                        curveNodeIds[Pair(nodeIndex, "T")] = curveNodeId
                        
                        writeCurveTriple(
                            writer,
                            curveId,
                            curveId + 1,
                            curveId + 2,
                            track.keyframes,
                            motion.interpolation,
                            "d|X", "d|Y", "d|Z"
                        )
                        
                        curveNodeId++
                        curveId += 3
                    }
                    is NjKeyframeTrack.EulerAngles -> {
                        writeAnimationCurveNode(writer, curveNodeId, "R", nodeIndex)
                        curveNodeIds[Pair(nodeIndex, "R")] = curveNodeId
                        
                        writeCurveTripleEuler(
                            writer,
                            curveId,
                            curveId + 1,
                            curveId + 2,
                            track.keyframes,
                            motion.interpolation
                        )
                        
                        curveNodeId++
                        curveId += 3
                    }
                    is NjKeyframeTrack.Scale -> {
                        writeAnimationCurveNode(writer, curveNodeId, "S", nodeIndex)
                        curveNodeIds[Pair(nodeIndex, "S")] = curveNodeId
                        
                        writeCurveTriple(
                            writer,
                            curveId,
                            curveId + 1,
                            curveId + 2,
                            track.keyframes,
                            motion.interpolation,
                            "d|X", "d|Y", "d|Z"
                        )
                        
                        curveNodeId++
                        curveId += 3
                    }
                    is NjKeyframeTrack.Quaternion -> {
                        // FBX uses Euler angles, so we would need to convert quaternions
                        // For now, skip quaternion tracks
                    }
                }
            }
        }
        
        return Pair(curveNodeId, curveId)
    }
    
