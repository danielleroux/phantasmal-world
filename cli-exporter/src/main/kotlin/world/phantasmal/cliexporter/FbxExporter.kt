package world.phantasmal.cliexporter

import world.phantasmal.psolib.fileFormats.ninja.*
import java.io.File
import java.io.PrintWriter

/**
 * Exports PSO animations to FBX ASCII format (version 7.4.0).
 * PSO uses 30 FPS frame rate.
 */
object FbxExporter {
    private const val PSO_FRAME_RATE = 30.0
    private const val KTIME_PER_SECOND = 46186158000L
    
    fun export(ninjaObject: NinjaObject<*, *>, motion: NjMotion, outputFile: File) {
        PrintWriter(outputFile).use { writer ->
            writeHeader(writer)
            writeGlobalSettings(writer, motion)
            writeDocuments(writer)
            writeDefinitions(writer, ninjaObject.boneCount(), motion)
            val curveIds = writeObjects(writer, ninjaObject, motion)
            writeConnections(writer, ninjaObject, motion, curveIds)
        }
    }
    
    private fun writeHeader(writer: PrintWriter) {
        writer.println("; FBX 7.4.0 project file")
        writer.println("; Generated by Phantasmal World CLI Exporter")
        writer.println("; ----------------------------------------------------")
        writer.println()
        writer.println("FBXHeaderExtension:  {")
        writer.println("    FBXHeaderVersion: 1003")
        writer.println("    FBXVersion: 7400")
        writer.println("    Creator: \"Phantasmal World CLI Exporter\"")
        writer.println("}")
        writer.println()
    }
    
